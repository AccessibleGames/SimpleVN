#!/usr/bin/env node
/**
 * Generate a single-game module for release builds.
 *
 *   node tools/build-game-module.mjs --game yukikaze1 [--out src/games.gen.ts]
 *
 * Reads games/<id>/game.json + content/, writes a module that exposes the menu
 * summary eagerly and the graph plus text packs as dynamic imports, so the app
 * boots on the small manifests and fetches the script when a game is opened.
 * Not hardcoded: whatever locales exist on disk are what get imported.
 */

import { existsSync } from "node:fs";
import { readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const args = process.argv.slice(2);
const read = (flag) => {
  const index = args.indexOf(flag);
  return index >= 0 ? args[index + 1] : undefined;
};

const gameId = read("--game");
if (!gameId) {
  console.error("usage: node tools/build-game-module.mjs --game <id> [--out src/games.gen.ts]");
  process.exit(1);
}

const dir = join("games", gameId);
const meta = JSON.parse((await readFile(join(dir, "game.json"), "utf8")).replace(/^\uFEFF/, ""));
const locales = (await readdir(join(dir, "content"), { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const hasGallery = existsSync(join(dir, "content", "gallery.json"));
const hasBg = existsSync(join(dir, "content", "bg.json"));
const hasSprites = existsSync(join(dir, "content", "sprites.json"));

const manifestImports = [
  ...(hasGallery ? [`import gallery from "../games/${gameId}/content/gallery.json";`] : []),
  ...(hasBg ? [`import bg from "../games/${gameId}/content/bg.json";`] : []),
  ...(hasSprites ? [`import sprites from "../games/${gameId}/content/sprites.json";`] : []),
];

const manifestFields = [
  ...(hasGallery ? ["    gallery: (gallery as unknown as { entries: GalleryEntry[] }).entries,"] : []),
  ...(hasBg ? ["    bg: (bg as unknown as { entries: GalleryEntry[] }).entries,"] : []),
  ...(hasSprites ? ["    sprites: (sprites as unknown as { entries: GalleryEntry[] }).entries,"] : []),
];

const packLoads = locales
  .map((locale) => `      "${locale}": (await import("../games/${gameId}/content/${locale}/pack.json")).default as unknown as Pack,`)
  .join("\n");

const source = `${manifestImports.join("\n")}${manifestImports.length ? "\n" : ""}import type {
  GalleryEntry,
  GameContent,
  GameSummary,
  Graph,
  Pack,
} from "./game";

/** Generated by tools/build-game-module.mjs — do not edit. */
const summary: GameSummary = {
  id: ${JSON.stringify(meta.id)},
  title: ${JSON.stringify(meta.title)},
  sourceLocale: ${JSON.stringify(meta.sourceLocale)},
  locales: ${JSON.stringify(locales)},
${manifestFields.length ? `${manifestFields.join("\n")}\n` : ""}};

export const games: GameSummary[] = [summary];

/** Script and packs are a few megabytes; they load when a game is opened. */
export async function loadGame(id: string): Promise<GameContent | null> {
  if (id !== summary.id) return null;

  const graph = (await import("../games/${gameId}/content/graph.json")).default as unknown as Graph;
  const packs: Record<string, Pack> = {
${packLoads.length ? `${packLoads}\n` : ""}  };

  return { ...summary, graph, packs };
}
`;

const out = read("--out") ?? join("src", "games.gen.ts");
await writeFile(out, source, "utf8");
console.log(
  `generated ${out} for ${gameId} (locales: ${locales.join(", ") || "none"}${hasGallery ? ", gallery" : ""})`,
);
